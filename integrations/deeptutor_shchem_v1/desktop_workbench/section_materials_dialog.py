def classroom_knowledge_card(card):
    """Project a fresh imported note; keep its sealed source and full statement.

    These reminder blocks are generated by the three knowledge importers, not
    user-authored edits. Original is retained intact for source rechecking.
    """
    value = deepcopy(validate_resource(card))
    if value['original']['kind'] != 'knowledge_note':
        raise ValueError('请选择教材知识讲解。')
    # Working edits retain block identity/order. Empty only the importer-created
    # reminders, so source provenance stays sealed without entering lesson text.
    for row in value['blocks']:
        if row['kind'] == 'text' and (row['role'] == 'teacher_note'
                                     or row['value'].startswith('适用范围与待核对处：')):
            row['value'] = ''
    return validate_resource(value)


class _GuardedCropPort:
    def __init__(self, facade, guard):
        self.facade, self.guard = facade, guard

    def __getattr__(self, name):
        value = getattr(self.facade, name)
        if name not in {'preparation_textbook_crop_page', 'preparation_textbook_crop_preview'}:
            return value
        def checked(*args, **kwargs):
            self.guard()
            result = value(*args, **kwargs)
            self.guard()
            return result
        return checked


