    def _base_request(self, kind, *, selection_scope=None):
        scope = selection_scope or ('knowledge' if kind == 'knowledge' else self._material_scope())
        request = {'kind': kind, 'context': deepcopy(self.context), 'selection_scope': scope}
        if scope == 'section':
            if not self._section_available() or kind == 'knowledge':
                raise ValueError('本节直接选材不能代替明确选择知识讲解。')
            return request
        if scope != 'knowledge' or self._selection is None or self._card is None:
            raise ValueError('请明确选择本节的一条真实知识讲解。')
        return {**request,
                'knowledge_selection': deepcopy(self._selection),
                'knowledge_card': classroom_knowledge_card(self._card),
                'knowledge_original': deepcopy(self._card['original'])}

    def _finish(self, kind, result, **extra):
        self._check()
        single_references = extra.pop('_single_references', None)
        scope = extra.pop('selection_scope', None)
        if kind == 'questions' and extra.get('question_mode') == 'linked':
            scope = 'knowledge'
        request = {**self._base_request(kind, selection_scope=scope), **deepcopy(extra)}
        if self.batch_mode:
            entries = [request]
            if (kind == 'questions' and request.get('question_mode') == 'browse'
                    and len(request['question_selections']) > 1):
                selections = request['question_selections']
                if (not isinstance(single_references, list) or len(single_references) != len(selections)
                        or any(not isinstance(ref, dict) or ref.get('selections') != [chosen] or ref.get('include_images') is not True
                               for chosen, ref in zip(selections, single_references))):
                    raise ValueError('请完整读取每道例题与原图，再加入授课清单。')
                entries = [{**deepcopy(request), 'question_selections': [deepcopy(chosen)],
                            'reference': deepcopy(ref)}
                           for chosen, ref in zip(selections, single_references)]
            if kind == 'handout_materials':
                from ..desktop_handout_material_handoff import validate_material_request
                material = validate_material_request(request['material_request'])
                arrays = {'knowledge': 'knowledge_requests', 'image': 'image_selections',
                          'question': 'question_selections'}
                order = material.get('selection_order', [
                    {'kind': name, 'index': index}
                    for name, array in arrays.items() for index in range(len(material[array]))])
                entries = []
                for entry in order:
                    one = deepcopy(material)
                    for name, array in arrays.items():
                        one[array] = ([deepcopy(material[array][entry['index']])]
                                      if name == entry['kind'] else [])
                    one['selection_order'] = [{'kind': entry['kind'], 'index': 0}]
                    # Each complete source selection stays sealed; splitting
                    # only lets it be arranged between textbook selections.
                    entries.append({**deepcopy(request), 'material_request': validate_material_request(one)})
            self._queued_requests.extend(entries)
            self._render_queue(len(self._queued_requests) - 1)
            self.status.setText('已加入授课清单。可继续阅读知识、教材图或讲义，再统一排序。')
            return
        self.request = request
        self.course_result = deepcopy(result)
        self.accept()

    def _render_queue(self, row=-1):
        with QSignalBlocker(self.queue_list):
            self.queue_list.clear()
            labels = {'knowledge': '知识讲解', 'textbook_images': '教材图',
                      'questions': '完整例题', 'handout_materials': '讲义知识与题'}
            for index, request in enumerate(self._queued_requests, 1):
                title = (request.get('knowledge_original', {}).get('title')
                         or request['context'].get('section_label') or '本节材料')
                label = labels[request['kind']]
                if request['kind'] == 'textbook_images':
                    title = request['crop_requests'][0].get('caption') or title
                elif request['kind'] == 'questions':
                    reference = request.get('reference') or request.get('linked_question', {}).get('reference', {})
                    title = reference.get('title') or reference.get('source_name') or title
                if request['kind'] == 'handout_materials':
                    material = request['material_request']
                    if material['knowledge_requests']:
                        selected = material['knowledge_requests'][0]
                        label = '讲义完整知识段'
                        title = selected.get('title') or title
                    elif material['image_selections']:
                        label = '讲义原图'
                        title = material['image_selections'][0]['title']
                    elif material['question_selections']:
                        label = '讲义完整例题'
                        title = material['question_selections'][0].get('title') or title
                self.queue_list.addItem(f"{index}. {label} · {title}")
            self.queue_list.setCurrentRow(min(row, len(self._queued_requests) - 1))
        self.queue_count.setText(f'本次授课顺序 · {len(self._queued_requests)} 项选材')
        self._controls()

    def _move_queue(self, step):
        row = self.queue_list.currentRow()
        destination = row + step
        if (self._active is not None or self._child is not None or row < 0
                or not 0 <= destination < len(self._queued_requests)):
            return
        self._check()
        self._queued_requests[row], self._queued_requests[destination] = self._queued_requests[destination], self._queued_requests[row]
        self._render_queue(destination)

    def _remove_queue(self):
        row = self.queue_list.currentRow()
        if self._active is not None or self._child is not None or row < 0:
            return
        self._check()
        self._queued_requests.pop(row)
        self._render_queue(row)

