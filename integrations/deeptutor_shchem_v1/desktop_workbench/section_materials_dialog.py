    def _check(self):
        if self._closed or self._stale or getattr(self.tasks, 'is_shutting_down', False):
            raise ValueError('本节选材窗口已关闭或当前课件已变化，请重新打开。')
        if self.guard is not None:
            self.guard()

    def _guard_current(self):
        if self._closed or self._stale:
            return
        try:
            self._check()
        except (ValueError, OSError) as exc:
            self._stale = True
            self._invalidate()
            self.status.setText(str(exc))
            self._guard_timer.stop()
            self._controls()

    def _recheck_context(self):
        from ..desktop_section_materials import (recheck_section_material_context,
            recheck_textbook_section_material_context)
        self._check()
        if self.context.get('entry_kind') == 'textbook_section':
            recheck_textbook_section_material_context(self.facade, self.context)
        else:
            recheck_section_material_context(self.facade, self.source_item,
                self.course_resources, self.image_assets, self.context)

    def _checked_card(self):
        if self._selection is None:
            raise ValueError('请明确选择本节的一条真实知识讲解。')
        self._recheck_context()
        card = import_knowledge_note(self.facade, deepcopy(self._selection))
        if self._card is not None and _source_content(card['original']) != _source_content(self._card['original']):
            raise ValueError('所选知识原内容已变化，请重新打开本节选材。')
        self._check()
        return card

    def _material_scope(self):
        return 'section' if self.context.get('entry_kind') == 'textbook_section' else 'knowledge'

    def _section_available(self):
        return (self._material_scope() == 'section' and self.context.get('status') == 'ready'
                and self.context.get('resource_id') is None and bool(self.context.get('book_key'))
                and bool(self.context.get('section_filter_key')))

    def _checked_scope(self, scope):
        if scope == 'knowledge':
            return self._checked_card()
        if scope != 'section' or not self._section_available():
            raise ValueError('请从真实教材的一节打开本节选材。')
        self._recheck_context()
        self._check()
        return deepcopy(self.context)

    def _material_title(self, scope=None):
        scope = scope or self._material_scope()
        return (self._card['original']['title'] if scope == 'knowledge' and self._card is not None
                else self.context.get('section_label') or '本节材料')

    def _links(self):
        if self.service is None:
            from ..desktop_knowledge_question_links import KnowledgeQuestionLinks
            self.service = KnowledgeQuestionLinks(self.facade)
        return self.service

    def _run(self, title, operation, ready):
        if self._closed or self._stale or self._active is not None:
            return
        try:
            self._check()
        except (ValueError, OSError) as exc:
            self.status.setText(str(exc))
            return
        self._serial += 1
        epoch, serial = self._epoch, self._serial
        context, selection, scope = deepcopy(self.context), deepcopy(self._selection), self._material_scope()
        self._active = 'starting'
        self.status.setText(title + '…')
        self._controls()
        def current():
            self._check()
            if (epoch != self._epoch or serial != self._serial or context != self.context
                    or selection != self._selection or scope != self._material_scope()):
                raise ValueError('章节或所选知识已变化，本次读取已取消。')
        def operation_checked():
            current()
            result = operation()
            current()
            return result
        def success(value):
            if self._closed or epoch != self._epoch or serial != self._serial:
                return
            self._active = None
            try:
                current()
                ready(value)
            except (ValueError, OSError, KeyError, TypeError) as exc:
                self.course_result = self.request = None
                self.status.setText(str(exc))
            self._controls()
        def failure(message):
            if self._closed or epoch != self._epoch or serial != self._serial:
                return
            self._active = None
            self.course_result = self.request = None
            self.status.setText(str(message))
            self._controls()
        try:
            identity = self.tasks.submit(title, operation_checked, on_success=success, on_failure=failure)
            if self._active == 'starting' and serial == self._serial:
                self._active = identity
        except (RuntimeError, TypeError) as exc:
            failure(str(exc))

    def _invalidate(self):
        self._epoch += 1
        self._serial += 1
        identity, self._active = self._active, None
        if identity not in (None, 'starting'):
            self.tasks.cancel(identity)
        if self._child is not None:
            self._child.reject()
        self.course_result = self.request = None
        self._card = self._images = self._knowledge_context = self._link_snapshot = None
        self._section_images = self._section_question_context = None
        self._section_loaded = False
        self._handout_sources = None
        self.knowledge_text.clear()
        self.image_list.clear()
        self.page_preview.set_row(None)
        self.question_list.clear()
        self.question_detail.clear()
        self.handout_source_list.clear()
        self.handout_hint.setText('可通读已导入讲义的知识、知识网与完整题。' if self._material_scope() == 'section'
                                 else '选择本节教材知识后，可从本课已用讲义继续选材。')

    def _show_context(self):
        self._invalidate()
        self._selection = None
        context = self.context
        if self._material_scope() == 'section':
            self.tabs.setTabText(1, '本节原页与图')
            self.tabs.setTabText(2, '完整 Word 题')
            self.image_list.setAccessibleName('本节完整原页与已登记教材图，明确选择后查看')
            self.knowledge_heading.setAccessibleName('当前真实教材节与可选知识讲解')
            self.crop_button.setText('框选本节原页或图，加入授课清单…' if self.batch_mode
                                     else '框选本节原页或图，加入本课…')
            with QSignalBlocker(self.tab_choice):
                for index in range(self.tabs.count()):
                    self.tab_choice.setItemText(index, self.tabs.tabText(index))
        self.heading.setText(context['book_label'] + (' · ' + context['section_label']
                                                      if context.get('section_label') else ''))
        with QSignalBlocker(self.section):
            self.section.clear()
            self.section.addItem('请选择原教材章节…', None)
            for row in context.get('section_choices', []):
                if row['book_key'] == context['book_key']:
                    self.section.addItem(row['section_label'], row['section_filter_key'])
            self.section.setCurrentIndex(max(0, self.section.findData(context.get('section_filter_key'))))
        self.section.setVisible(context['status'] == 'section_selection_required')
        with QSignalBlocker(self.knowledge_list):
            self.knowledge_list.clear()
            chosen = -1
            for row in context.get('knowledge_options', []):
                if row['book_key'] != context['book_key'] or row['section_filter_key'] != context['section_filter_key']:
                    continue
                item = QListWidgetItem(str(row['title']))
                item.setData(Qt.ItemDataRole.UserRole, deepcopy(row))
                self.knowledge_list.addItem(item)
                if knowledge_selection(row) == context.get('knowledge_selection'):
                    chosen = self.knowledge_list.count() - 1
            self.knowledge_list.setCurrentRow(chosen)
