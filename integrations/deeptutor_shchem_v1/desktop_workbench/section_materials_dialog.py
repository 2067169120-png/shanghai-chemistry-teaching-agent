    def _exec_child(self, dialog, *, selection_scope=None):
        try:
            self._check()
        except (ValueError, OSError):
            dialog.reject()
            dialog.deleteLater()
            raise
        epoch, serial, selection = self._epoch, self._serial, deepcopy(self._selection)
        context, material_scope = deepcopy(self.context), self._material_scope()
        scope = selection_scope or material_scope
        if scope not in {'section', 'knowledge'} or (scope == 'section' and not self._section_available()):
            dialog.reject()
            dialog.deleteLater()
            raise ValueError('本次选材范围无效，请重新打开本节。')
        self._child = dialog
        self._controls()
        try:
            result = dialog.exec()
            self._check()
            if (epoch != self._epoch or serial != self._serial or selection != self._selection
                    or context != self.context or material_scope != self._material_scope()):
                raise ValueError('章节、知识或选材范围已变化，本次选材已取消。')
            return result
        finally:
            self._child = None
            dialog.deleteLater()
            self._controls()

