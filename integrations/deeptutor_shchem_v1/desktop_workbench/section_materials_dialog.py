    def _open_handout_materials(self, candidate):
        from ..desktop_section_handout_sources import recheck_course_handout_source
        scope = self._material_scope()
        def read():
            self._checked_scope(scope)
            if candidate is not None:
                recheck_course_handout_source(self.facade, self.course_resources, candidate)
            return deepcopy(candidate)
        def ready(checked_candidate):
            from .handout_material_workspace import HandoutMaterialWorkspace
            dialog = HandoutMaterialWorkspace(self.facade, self.tasks, self,
                initial_source=deepcopy(checked_candidate['source']) if checked_candidate is not None else None)
            dialog.setWindowTitle(self._material_title(scope) + ' · 讲义知识与知识网')
            dialog.confirm.setText(('将讲义选材加入授课清单' if self.batch_mode else '将讲义选材加入本课')
                                   if scope == 'section' else
                                   ('将知识与讲义选材加入授课清单' if self.batch_mode else '将知识与讲义选材加入本课'))
            if self._exec_child(dialog, selection_scope=scope) != QDialog.DialogCode.Accepted or not dialog.request:
                return
            material_request = deepcopy(dialog.request)
            if (not isinstance(material_request, dict) or (checked_candidate is not None
                    and material_request.get('source') != checked_candidate['source'])):
                raise ValueError('本次讲义选材与已选来源不一致，请重新阅读。')
            def checked():
                read()
                return None
            self._run('核对本节与讲义选材' if scope == 'section' else '核对当前知识与讲义选材', checked, lambda result:
                self._finish('handout_materials', result, material_request=material_request,
                             course_handout_source=checked_candidate))
        self._run('打开本课讲义选材', read, ready)

