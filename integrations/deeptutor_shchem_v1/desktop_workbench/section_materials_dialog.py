    def _select_knowledge(self, item, *_):
        self._invalidate()
        self._selection = None
        if item is None or self._closed or self._stale:
            self._controls()
            if item is None and self._section_available():
                self._load_section_materials()
            return
        row = deepcopy(item.data(Qt.ItemDataRole.UserRole))
        self._selection = knowledge_selection(row)
        self.knowledge_heading.setText(row['title'])
        self.image_hint.setText('正在读取这条知识的原页与同节图候选…')
        self.question_hint.setText('正在读取这条知识已保存的例题关联…')
        def read():
            card = self._checked_card()
            value = {'card': card, 'images': None, 'links': [], 'knowledge_context': None,
                     'snapshot': None, 'image_error': '', 'question_error': ''}
            try:
                value['images'] = (section_textbook_options(self.facade, deepcopy(self.context))
                    if self._material_scope() == 'section' else knowledge_textbook_options(self.facade, card))
            except (ValueError, OSError) as exc:
                value['image_error'] = str(exc)
            try:
                service = self._links()
                value['knowledge_context'] = service.knowledge_context(card)
                value['links'] = service.list(card, assess=True)
                value['snapshot'] = service.snapshot()
            except (ValueError, OSError) as exc:
                value['question_error'] = str(exc)
            if self._material_scope() == 'section':
                try:
                    value['section_question_context'] = section_question_context(self.facade, deepcopy(self.context))
                except (ValueError, OSError) as exc:
                    value['section_question_error'] = str(exc)
            return value
        def ready(value):
            self._card = value['card']
            self._images = value['images']
            if self._material_scope() == 'section':
                self._section_loaded = True
                self._section_images = value['images']
                self._section_question_context = value.get('section_question_context')
            self._knowledge_context = value['knowledge_context']
            self._link_snapshot = value['snapshot']
            projected = classroom_knowledge_card(self._card)
