def course_route(route: str) -> tuple[str, str]:
    return _ROUTES.get(_LESSON_ROUTE.get(route, "other"), _ROUTES["other"])


def teacher_design_starter(route: str) -> str:
    """Teacher-editable text, persisted through the existing delivery field."""
    label, sequence = course_route(route)
    return (
        f"【{label}课授课结构，可直接改写】\n"
        f"课堂推进：{sequence}\n"
        "本课调整：以表单中的章节、课时和目标为准；在此补充必讲、略讲、暂不讲的内容。\n"
        "内容依据：先研读对应Word讲义的知识总结、得分速记和例题，再与教材原文、"
        "知识点及图片对应。已提供且适合本课的教材图文优先，保留完整定义和条件。\n"
        "讲练安排：每个主要学习段明确教师主讲例题、学生独立练习及反馈；"
        "优先采用讲义配套题，不为凑数添加重复题。题目使用范围仍以本次授权为准。\n"
        "笔记呈现：每段留出整理时间，给出已填写的知识表或分层短句，"
        "包括判断条件、典型表达和易错理由；课末对照同一框架查漏，不重新抄写全部内容。\n"
        "页面与图片：首屏用章节名。观察、解释、例题、独立练习、反馈、笔记各有用途，"
        "按需要合并或拆页，不每页机械套流程；图片必须参与提问和解释。\n"
        "投影对象：约40人普通课堂，优先照顾后排阅读。页标题用简短学科名称或课堂问题，"
        "同一知识段可沿用同一标题；不要把主讲示范、核对与依据、课程回扣等教学设计话语当标题。"
        "正文呈现完整定义、题干、方程式与笔记；教学意图和操作说明写入教师备注。\n"
        "课时调整：逐课时安排起点、主要任务和出口检查；材料偏多时先移出拓展，"
        "保留思考、讲评及记写时间。可在此修改讲练侧重、重点难点、板书和版式。"
    )


def course_composition_contract(route: str) -> str:
    label, sequence = course_route(route)
    return (
        f"\n课程编排底稿 {COURSE_DESIGN_REVISION}｜当前课型：{label}\n"
        "这是一份面向学生授课的课程，不是知识条目转幻灯片。先完成可检查的课程组织，"
        "再展开页面；不输出私有思考过程，交付简洁的设计结果即可。\n"
        f"课型默认推进：{sequence}\n"
        "教师可调整层：advanced.template_and_delivery是教师的授课结构、笔记和呈现偏好；"
        "非空时优先落实其明确安排，未指定处采用上述课型默认值。课型切换不抹去教师自写内容。"
        "它不解除来源核验、题目授权、化学正确性及输出结构约束；若与课时或资料发生矛盾，"
        "在uncertainties指出具体取舍，不静默改变必讲要求。\n"
        "先按以下顺序形成课程，再生成slides：\n"
        "A 内容取舍：逐项对应核心知识、教材原句/图、讲义总结/例题、学生最终应会的任务；"
        "标明必讲、支撑或拓展。用真实页码或区块编号，缺少原文、图片或完整题面时明确缺口。"
        "仅有文件名不算读过讲义，已有来源也不等于其中每句都正确。\n"
        "B 学习段：把相互依赖的内容组织成少量连续段，不按知识点数量一项配一页。"
        "在每段首张slide.teacher_notes用简短‘课程段’说明：承接什么已有结论、"
        "本段要解决什么问题、使用哪些来源、学生留下什么产出、达到什么标准才进入下一段。"
        "activities及lesson_stages据此组织，使用既有字段，不另造JSON顶层字段。\n"
        "C 段内展开：可采用观察材料→解释概念→教师例题→独立练习→反馈→笔记，"
        "也可按课型先诊断再补讲。不是每段都要六种页面；重点是上一项产出会被下一项使用。"
        "跨段过渡在学生可见content用一句实际问题承接，说明前一发现为什么引出下一问题；"
        "不要把这句要求本身写上PPT，也不要只在备注宣称逻辑连贯。\n"
        "D 例题与应试：主讲题展示完整获准题面、抓条件、选判据、推理及规范表达。"
        "学生练习检查同一方法的独立使用；教师备注说明它比主讲题改变了什么条件、"
        "表示方式或认知要求，完全重复者合并。不因题号多就宣称训练充分。"
        "反馈要显示答案与理由；常考总结以讲义考向为依据，呈现‘条件—判断方法—"
        "典型表达—易错理由’，不编造考频或官方评分标准。\n"
        "E 图文与笔记：优先安排本课相关教材图、定义原句图以及讲义中的有效题图；"
        "为每张图确定观察对象、所得证据及随后使用它的结论或习题。缺图时列具体需求。"
        "教材原句负责锚定概念，完整知识表负责整理，例题负责展示方法，三者不能相互替代。"
        "先看图、解释后再停顿记录；投影上给可直接记的内容，备注不代替学生笔记。\n"
        "F 整课收束：让学生用所得方法回答开场问题，并与开头诊断对照；"
        "各段笔记合成一张关系清楚的复习框架，多页可分块，不强塞一页小字。"
        "逐课时留思考、反馈和记写时间，超时先压缩重复与拓展；不固定为 9—14 页，"
        "不以页数、图数、题量或提示词长度作为质量结论。\n"
        "输出前在首个lesson_stage.materials写简短‘课程取舍’：主要来源、"
        "采用的学习段与拓展去向；在各段备注留下上述对应依据供教师检查，"
        "不要在学生页面放教材分析、设计说明或来源审计报告。\n"
        "G 课堂投影：默认服务约40人班级，不套组会汇报的小页眉、侧栏和稀疏提纲。"
        "标题用简短学科知识名称或学生要回答的问题，连续页面可保留同一知识标题；"
        "不使用‘主讲示范’‘核对与依据’‘课程回扣’等教师设计语言充当主标题。"
        "‘例题’‘练习’可作为简短任务标记，但题干和图像是主内容。"
        "普通正文及题干建议28—32pt、标题36—44pt，表格必要时拆页；这只是可调整起点，"
        "不是国家平台规定或后排可读性的实测结论。不靠不断缩小字号塞完材料。"
        "图文须有主次，观察图尽量放大、保留必要标签；来源简注可小，关键知识不能藏入小字。"
        "同一页只保留一套必要编号，不给题干、每个选项和解释再套自动数字。"
        "逐步呈现须真实实现；静态导出采用题目页与解答页分开，不能声称有动画。\n"
    )
