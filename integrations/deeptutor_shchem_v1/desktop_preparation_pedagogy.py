        "跨段过渡在学生可见content用一句实际问题承接，说明前一发现为什么引出下一问题；"
        "不要把这句要求本身写上PPT，也不要只在备注宣称逻辑连贯。\n"
        "D 例题与应试：主讲题展示完整获准题面、抓条件、选判据、推理及规范表达。"
